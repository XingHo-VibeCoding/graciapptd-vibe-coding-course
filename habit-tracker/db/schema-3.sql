-- ============================================================================
-- 【Day 22】给 checkins 加「软删除」标记 —— 删除不真删行
-- ----------------------------------------------------------------------------
-- 需求：课程 Day 22 要上线 DELETE 接口，并留了一个余力加练——
--   「不真删数据，只在记录上加一个 is_deleted 标记、查询时跳过，删错了还能找回」。
--
-- 【今天要掌握的问题】删除为什么比新增更容易出事？删完在三层都要有"确认"——
--   新增出错，最坏是库里多一条垃圾数据：用户看得见它、随手就能删掉，代价可逆。
--   删除出错，是让一行数据**从所有界面里消失**：真删之后没有任何入口能看到它，
--   点错一下 = 不可逆的数据丢失。所以删除这件事要在三个层面各加一道防线：
--     ① 交互层：前端 `confirm()` 二次确认（PRD A4，Day 13 就有）
--     ② 服务层：按 `uid` 限定删除范围 —— 只按 id 删是不够的，
--        查到行但 uid 不是本人 → 403「无权删除这条待办」，从根上挡住"删到别人的数据"
--     ③ 存储层：**不真删，只打标记**（本文件这一列）—— 万一前两道都漏了，还能捞回来
--
-- 为什么把 ③ 做成默认行为、而不是"以后再说"：
--   这条防线的成本极低（一个 boolean 列 + 查询带一个条件），
--   而它挡住的后果（把用户的心情记录、打卡历史删没了）是不可逆的。
--   对"个人自律记录"这种数据，真删几乎永远不是用户想要的。
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1) checkins.is_deleted —— 软删除标记
-- ---------------------------------------------------------------------------
-- 默认 FALSE、NOT NULL：历史 9 行与以后新增的行都自动是"没删过"，
--   所以加这一列**不影响任何既有数据与既有接口**（加列本身是向后兼容的）。
ALTER TABLE checkins ADD COLUMN IF NOT EXISTS is_deleted BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN checkins.is_deleted IS
  '软删除标记：true = 用户在界面上删掉了这条；默认 FALSE。查询默认跳过已删行（见 api-contract.md §1.7 与 §三 GET 接口），物理行仍在，删错可恢复';


-- ---------------------------------------------------------------------------
-- 2) 刻意没建的新索引（说清楚，免得以为是漏了）
-- ---------------------------------------------------------------------------
-- 已删行的过滤条件是 `is_deleted = false`，最常用的查询仍然是「某人的某一天」，
-- Day 16 建的 checkins_uid_date_idx (uid, date) 已经能把这批行缩到很小，
-- 再按 is_deleted 过滤几乎不花代价（本项目的数据量级是"一个人的打卡历史"）。
-- 所以**不新建索引**：无依据地加索引只会让写入变慢、让"改表脚本"越来越长。
-- 真到了数据量大到需要过滤索引那天（例如 10 万行以上），再补
--   CREATE INDEX ... ON checkins (uid, date) WHERE is_deleted = false;
-- 不迟，且届时本文件追加一节即可。


-- ---------------------------------------------------------------------------
-- 3) 执行结果自述（跑完在 SQL 编辑器里应看到这两行）
-- ---------------------------------------------------------------------------
SELECT 'checkins.is_deleted 列已就绪' AS "检查", count(*)::text AS "结果"
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'checkins' AND column_name = 'is_deleted'
UNION ALL
SELECT '现有行全部为未删除（is_deleted = false）', count(*)::text
FROM checkins
WHERE is_deleted = false;


