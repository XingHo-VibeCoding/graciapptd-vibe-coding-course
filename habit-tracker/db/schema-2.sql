-- ============================================================================
-- 【Day 18】给 checkins 加「重复提交防护」——客户端幂等键
-- ----------------------------------------------------------------------------
-- 需求：课程 Day 18 要求「重复提交被拒」。
--
-- 撞上的旧决策：Day 16 在 seed.sql 里明确记录过 ——
--   checkins **没有天然唯一键**（"写周报"理论上一天可以出现两次），
--   所以当时刻意没给业务表加「同一天 + 同名」的唯一约束。
--   今天若直接加 UNIQUE (uid, date, text)，等于推翻那条决策，而且会把
--   「合法地想加两条同名待办」也一起拒掉 —— 那是误伤，不是防护。
--
-- 所以改用**幂等键（idempotency key）**：
--   前端每点一次「添加」，就现场生成一个一次性的 clientReqId（uuid），随请求带上；
--   数据库把 (uid, clientReqId) 设为唯一 —— 于是
--     · 同一个「添加动作」被重发（用户双击 / 网络超时后客户端自动重试）
--       → 带着同一个 clientReqId → 第二次被数据库挡下 ✅ 这才是"重复提交"
--     · 用户真的想加两条同名待办
--       → 两次是两次不同的「添加动作」，clientReqId 不同 → 照常写入 ✅ 不误伤
--   「是不是重复」由**客户端的动作 id** 表达，而不是由**内容是否相同**去猜。
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1) checkins.client_req_id —— 客户端幂等键
-- ---------------------------------------------------------------------------
-- 允许为空：Day 16 那 8 行种子数据没有这个值，加列不会违反任何约束；
--   NULL 的语义 = "这次写入没有要求幂等保护"（curl 手测、历史数据）。
ALTER TABLE checkins ADD COLUMN IF NOT EXISTS client_req_id TEXT;

COMMENT ON COLUMN checkins.client_req_id IS
  '客户端幂等键：一次"添加动作"一个唯一值（uuid），用于识别重复提交；NULL 表示未启用幂等保护';


-- ---------------------------------------------------------------------------
-- 2) 部分唯一索引：(uid, client_req_id)
-- ---------------------------------------------------------------------------
-- 为什么加 WHERE client_req_id IS NOT NULL（部分索引）？
--   NULL 在唯一索引里"彼此不相等"，不排除的话语义含糊；显式写成
--   "只对填了 key 的行去重"，规则一眼可读，也不影响历史 NULL 行。
--
-- 为什么唯一键里必须带 uid，而不是只 unique(client_req_id)？
--   幂等键空间要按用户隔离：不同用户的 uuid 万一撞了，绝不能互相冲突
--   （否则 A 的重复提交会挡住 B 的正常写入）。uid 进唯一键 = 防串号。
CREATE UNIQUE INDEX IF NOT EXISTS checkins_uid_reqid_uniq
  ON checkins (uid, client_req_id)
  WHERE client_req_id IS NOT NULL;


-- ---------------------------------------------------------------------------
-- 3) 执行结果自述（跑完在 SQL 编辑器里应看到这两行）
-- ---------------------------------------------------------------------------
SELECT 'checkins.client_req_id 列已就绪' AS "检查", count(*)::text AS "结果"
FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'checkins' AND column_name = 'client_req_id'
UNION ALL
SELECT 'checkins_uid_reqid_uniq 索引已就绪', count(*)::text
FROM pg_indexes
WHERE schemaname = 'public' AND indexname = 'checkins_uid_reqid_uniq';


